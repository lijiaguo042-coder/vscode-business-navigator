const vscode = require('vscode');
const assert = require('node:assert/strict');
const path = require('node:path');
/** 通过真实扩展宿主执行导航、引用、侧栏和编辑失效验收。 */
exports.run=async function run(){
 const root=vscode.workspace.workspaceFolders[0].uri.fsPath;
 const uri=name=>vscode.Uri.file(path.join(root,name));
 const extension=vscode.extensions.getExtension('local-tools.vscode-business-navigator');
 assert.ok(extension,'插件必须发现'); await extension.activate();
 const vueDoc=await vscode.workspace.openTextDocument(uri('resources/js/views/A.vue'));
 assert.equal(vueDoc.languageId,'vue','无第三方插件时 Vue 文件也应注册为 vue 语言');
 const vuePos=vueDoc.positionAt(vueDoc.getText().indexOf('list();')+1);
 const vueDefs=await vscode.commands.executeCommand('vscode.executeDefinitionProvider',vueDoc.uri,vuePos);
 assert.ok(vueDefs.some(d=>(d.uri??d.targetUri).fsPath.endsWith('api/items.js')),'Vue 调用应跳转 API');
 if(process.env.BUSINESS_NAV_EXTENSIONS_DIR){
   for(const id of ['bmewburn.vscode-intelephense-client','octref.vetur']){
     const companion=vscode.extensions.getExtension(id);assert.ok(companion,`兼容插件 ${id} 必须安装`);await companion.activate();assert.ok(companion.isActive);
   }
   console.log('HOST: Intelephense + Vetur activated alongside navigator');
 }
 const api=await vscode.workspace.openTextDocument(uri('resources/js/api/items.js'));
 const editor=await vscode.window.showTextDocument(api);
 const pos=api.positionAt(api.getText().indexOf("'/items'")+2);
 editor.selection=new vscode.Selection(pos,pos);
 let defs=await vscode.commands.executeCommand('vscode.executeDefinitionProvider',api.uri,pos);
 assert.ok(defs.some(d=>(d.uri??d.targetUri).fsPath.endsWith('routes/api.php')),'URL 默认必须定位路由');
 const config=vscode.workspace.getConfiguration('businessNavigator',api.uri);
 const apiRefs=await vscode.commands.executeCommand('vscode.executeReferenceProvider',api.uri,pos);
 assert.ok(apiRefs.some(r=>r.uri.fsPath.endsWith('A.vue')),'URL 查找引用仍应解析到控制器的反向调用');
 try{
   await config.update('apiDefinitionTarget','controller',vscode.ConfigurationTarget.WorkspaceFolder);
   defs=await vscode.commands.executeCommand('vscode.executeDefinitionProvider',api.uri,pos);
   assert.ok(defs.some(d=>(d.uri??d.targetUri).fsPath.endsWith('ItemsController.php')),'切换配置后 URL 必须直接定位控制器');
 }finally{await config.update('apiDefinitionTarget',undefined,vscode.ConfigurationTarget.WorkspaceFolder);}
 console.log('HOST: 默认路由、控制器配置切换和 URL 引用通过');
 await vscode.commands.executeCommand('businessNavigator.showChain');
 if(process.env.BUSINESS_NAV_PREVIEW){
   console.log('HOST PREVIEW: 90 秒交互验收窗口');
   await new Promise(resolve=>setTimeout(resolve,90000));
   await vscode.window.showTextDocument(api);editor.selection=new vscode.Selection(pos,pos);
 }
 await vscode.commands.executeCommand('businessNavigator.togglePin');
 await vscode.commands.executeCommand('businessNavigator.togglePin');
 await vscode.commands.executeCommand('editor.action.revealDefinition');
 assert.ok(vscode.window.activeTextEditor.document.uri.fsPath.endsWith('routes/api.php'),'F12 命令默认必须打开路由');
 const routeEditor=vscode.window.activeTextEditor;
 const handlerPos=routeEditor.document.positionAt(routeEditor.document.getText().indexOf('ItemsController@index')+2);
 routeEditor.selection=new vscode.Selection(handlerPos,handlerPos);
 await vscode.commands.executeCommand('editor.action.revealDefinition');
 assert.ok(vscode.window.activeTextEditor.document.uri.fsPath.endsWith('ItemsController.php'),'F12 命令必须打开控制器');
 const controller=await vscode.workspace.openTextDocument(uri('app/Http/Controllers/ItemsController.php'));
 const methodPos=controller.positionAt(controller.getText().indexOf('function index')+'function '.length);
 const refs=await vscode.commands.executeCommand('vscode.executeReferenceProvider',controller.uri,methodPos);
 assert.ok(refs.some(r=>r.uri.fsPath.endsWith('A.vue')),'反向引用应包括 Vue 实际调用');
 const servicePos=controller.positionAt(controller.getText().indexOf('->list')+3);
 defs=await vscode.commands.executeCommand('vscode.executeDefinitionProvider',controller.uri,servicePos);
 assert.ok(defs.some(d=>(d.uri??d.targetUri).fsPath.endsWith('ItemService.php')),'注入服务方法应可跳转');console.log('HOST: F12, references and service passed');
 const service=await vscode.workspace.openTextDocument(uri('app/Services/ItemService.php'));
 const serviceEditor=await vscode.window.showTextDocument(service);
 const facadePos=service.positionAt(service.getText().indexOf('getBanList')+2);
 serviceEditor.selection=new vscode.Selection(facadePos,facadePos);
 defs=await vscode.commands.executeCommand('vscode.executeDefinitionProvider',service.uri,facadePos);
 assert.ok(defs.some(d=>(d.uri??d.targetUri).fsPath.endsWith('/Utils/GameUtils.php')),'服务内 Facade 调用必须提供实际实现');
 await vscode.commands.executeCommand('editor.action.revealDefinition');
 assert.ok(vscode.window.activeTextEditor.document.uri.fsPath.endsWith('/Utils/GameUtils.php'),'Facade F12 必须打开实现而非注释声明');
 const implementation=vscode.window.activeTextEditor.document;
 const implementationRefs=await vscode.commands.executeCommand('vscode.executeReferenceProvider',implementation.uri,implementation.positionAt(implementation.getText().indexOf('getBanList')+2));
 assert.ok(implementationRefs.some(r=>r.uri.fsPath.endsWith('ItemService.php')),'实现方法反向引用必须包含服务');
 assert.ok(implementationRefs.some(r=>r.uri.fsPath.endsWith('A.vue')),'实现方法反向引用必须包含上游 Vue 页面');
 const provider=await vscode.workspace.openTextDocument(uri('app/Providers/AppServiceProvider.php'));
 await vscode.window.showTextDocument(provider);
 const bindingEdit=new vscode.WorkspaceEdit();
 bindingEdit.replace(provider.uri,new vscode.Range(provider.positionAt(0),provider.positionAt(provider.getText().length)),provider.getText().replace('new GameUtils','new ReplacementGameUtils'));
 await vscode.workspace.applyEdit(bindingEdit);
 defs=await vscode.commands.executeCommand('vscode.executeDefinitionProvider',service.uri,facadePos);
 assert.ok(defs.some(d=>(d.uri??d.targetUri).fsPath.endsWith('/Utils/ReplacementGameUtils.php')),'未保存绑定修改后必须跳转新实现');
 await vscode.commands.executeCommand('workbench.action.revertAndCloseActiveEditor');
 defs=await vscode.commands.executeCommand('vscode.executeDefinitionProvider',service.uri,facadePos);
 assert.ok(defs.some(d=>(d.uri??d.targetUri).fsPath.endsWith('/Utils/GameUtils.php')),'丢弃绑定修改后必须恢复原实现');
 console.log('HOST: 服务 Facade 实现 F12、反向 Vue 引用和绑定编辑丢弃通过');
 const configPos=service.positionAt(service.getText().indexOf('application.upload_zipfile_v2')+15);
 const configEditor=await vscode.window.showTextDocument(service);
 configEditor.selection=new vscode.Selection(configPos,configPos);
 defs=await vscode.commands.executeCommand('vscode.executeDefinitionProvider',service.uri,configPos);
 assert.ok(defs.some(d=>(d.uri??d.targetUri).fsPath.endsWith('config/application.php')),'config helper 必须定位配置文件');
 await vscode.commands.executeCommand('editor.action.revealDefinition');
 const configDoc=vscode.window.activeTextEditor.document;
 assert.ok(configDoc.uri.fsPath.endsWith('config/application.php'),'配置 F12 必须打开配置文件');
 const configDefinition=defs.find(d=>(d.uri??d.targetUri).fsPath.endsWith('config/application.php'));
 const configRange=configDefinition.range??configDefinition.targetSelectionRange;
 assert.equal(configDoc.getText(configRange),"'upload_zipfile_v2'",'配置定义范围应精确覆盖键名');
 assert.ok(vscode.window.activeTextEditor.selection.active.isEqual(configRange.start),'配置 F12 光标应落在键名起点');
 const configRefs=await vscode.commands.executeCommand('vscode.executeReferenceProvider',configDoc.uri,configDoc.positionAt(configDoc.getText().indexOf('upload_zipfile_v2')+2));
 assert.ok(configRefs.some(r=>r.uri.fsPath.endsWith('ItemService.php')),'配置声明应可反查调用位置');
 const configEdit=new vscode.WorkspaceEdit();
 configEdit.replace(configDoc.uri,new vscode.Range(configDoc.positionAt(0),configDoc.positionAt(configDoc.getText().length)),configDoc.getText().replace('upload_zipfile_v2','renamed'));
 await vscode.workspace.applyEdit(configEdit);
 defs=await vscode.commands.executeCommand('vscode.executeDefinitionProvider',service.uri,configPos);
 assert.equal(defs.length,0,'未保存配置改名后不能保留旧跳转');
 await vscode.commands.executeCommand('workbench.action.revertAndCloseActiveEditor');
 defs=await vscode.commands.executeCommand('vscode.executeDefinitionProvider',service.uri,configPos);
 assert.ok(defs.some(d=>(d.uri??d.targetUri).fsPath.endsWith('config/application.php')),'丢弃配置修改后恢复定义');
 console.log('HOST: 配置键 F12、反向引用、未保存编辑和丢弃通过');
 const dynamicEditor=await vscode.window.showTextDocument(service);
 const dynamicRoot=service.positionAt(service.getText().indexOf('huawei')+2);
 defs=await vscode.commands.executeCommand('vscode.executeDefinitionProvider',service.uri,dynamicRoot);
 assert.ok(defs.some(d=>(d.uri??d.targetUri).fsPath.endsWith('config/huawei.php') && (d.range??d.targetSelectionRange).start.line===0),'动态配置文件段应定位文件入口');
 const dynamicGroup=service.positionAt(service.getText().indexOf('game_list')+2);
 dynamicEditor.selection=new vscode.Selection(dynamicGroup,dynamicGroup);
 defs=await vscode.commands.executeCommand('vscode.executeDefinitionProvider',service.uri,dynamicGroup);
 const groupDefinition=defs.find(d=>(d.uri??d.targetUri).fsPath.endsWith('config/huawei.php'));
 assert.ok(groupDefinition,'动态配置的静态前缀应有定义');
 await vscode.commands.executeCommand('editor.action.revealDefinition');
 const huawei=vscode.window.activeTextEditor.document;
 assert.ok(huawei.uri.fsPath.endsWith('config/huawei.php'),'静态前缀 F12 必须打开对应配置文件');
 const groupRange=groupDefinition.range??groupDefinition.targetSelectionRange;
 assert.equal(huawei.getText(groupRange),"'game_list'");
 assert.ok(vscode.window.activeTextEditor.selection.active.isEqual(groupRange.start),'静态前缀 F12 必须落在 game_list 键名起点');
 for(const offset of [service.getText().indexOf('{$gameid}')+3,service.getText().indexOf('.appid')+2]){
   defs=await vscode.commands.executeCommand('vscode.executeDefinitionProvider',service.uri,service.positionAt(offset));
   assert.equal(defs.length,0,'动态配置变量和后缀不应误跳到静态前缀');
 }
 console.log('HOST: 动态配置静态前缀 F12 和动态边界通过');
 await vscode.window.showTextDocument(api);
 const edit=new vscode.WorkspaceEdit(); edit.replace(api.uri,new vscode.Range(api.positionAt(0),api.positionAt(api.getText().length)),api.getText().replace('/items','/missing'));
 await vscode.workspace.applyEdit(edit);
 defs=await vscode.commands.executeCommand('vscode.executeDefinitionProvider',api.uri,pos);
 assert.equal(defs.length,0,'未保存编辑不能保留旧路由');
 await vscode.commands.executeCommand('workbench.action.revertAndCloseActiveEditor');
 const reopened=await vscode.workspace.openTextDocument(api.uri);
 await vscode.window.showTextDocument(reopened);
 defs=await vscode.commands.executeCommand('vscode.executeDefinitionProvider',api.uri,pos);
 assert.ok(defs.length>0,'关闭并丢弃未保存内容后自动恢复磁盘索引');
 await vscode.commands.executeCommand('businessNavigator.rebuild');
 defs=await vscode.commands.executeCommand('vscode.executeDefinitionProvider',api.uri,pos);
 assert.ok(defs.length>0,'恢复源码后可重建');console.log('HOST: edit/discard/rebuild passed');
 const foldersChanged=new Promise(resolve=>{const listener=vscode.workspace.onDidChangeWorkspaceFolders(()=>{listener.dispose();resolve();});});
 vscode.workspace.updateWorkspaceFolders(vscode.workspace.workspaceFolders.length,0,{uri:uri('routes')});
 await foldersChanged;
 const routeDoc=await vscode.workspace.openTextDocument(uri('routes/api.php'));
 const nestedEdit=new vscode.WorkspaceEdit();nestedEdit.replace(routeDoc.uri,new vscode.Range(routeDoc.positionAt(0),routeDoc.positionAt(routeDoc.getText().length)),"<?php Route::post('items','ItemsController@index');");
 await vscode.workspace.applyEdit(nestedEdit);
 defs=await vscode.commands.executeCommand('vscode.executeDefinitionProvider',api.uri,pos);
 assert.equal(defs.length,0,'嵌套工作区内编辑同时失效父索引');
 // 恢复路由，继续验证文件重命名。
 const restore=new vscode.WorkspaceEdit();restore.replace(routeDoc.uri,new vscode.Range(routeDoc.positionAt(0),routeDoc.positionAt(routeDoc.getText().length)),"<?php Route::get('items','ItemsController@index');");
 await vscode.workspace.applyEdit(restore);await routeDoc.save();
 const rename=new vscode.WorkspaceEdit();rename.renameFile(uri('routes/api.php'),uri('routes/renamed.php'));
 await vscode.workspace.applyEdit(rename);await vscode.commands.executeCommand('businessNavigator.rebuild');
 defs=await vscode.commands.executeCommand('vscode.executeDefinitionProvider',api.uri,pos);
 assert.equal(defs.length,0,'路由文件重命名后失效');
 console.log('HOST PASS: 定义、F12命令、服务、Vue反向引用、侧栏命令、固定、未保存编辑和重命名');
};
